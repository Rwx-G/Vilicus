//! The steps of `doc/key-management.md` section 2 that authenticate a member public key
//! before HK is wrapped to it.
//!
//! The passphrase, the DEK and the wrapping of private keys by the DEK are outside this
//! spike: [`MemberSecrets`] stands for what the member's unlock recovers, and holds the
//! private keys directly.

use std::fmt;
use std::path::Path;

use aws_lc_rs::rand::{SecureRandom, SystemRandom};

use crate::encoding::{
    EnrollKeyWrap, HkWrap, PubkeyMac, Tagged32, alg, label, mac_input, versioned_context,
};
use crate::error::Error;
use crate::primitives::{
    HpkePrivateKey, Secret32, X25519_LEN, aead_open, aead_seal, constant_time_eq, hkdf_sha256,
    hmac_sha256, hmac_sha256_verify, hpke_generate_keypair, hpke_open, hpke_public_bytes,
    hpke_seal,
};
use crate::store::{MemberRecord, MemberState, Store, check_member_id};

/// Length of an enrollment token: 128 random bits.
pub const TOKEN_LEN: usize = 16;
/// HK version created with the first member.
pub const FIRST_HK_VERSION: u32 = 1;

/// A single-use enrollment token, printed by `vilicus member add`. Never printed by `Debug`.
pub struct EnrollmentToken([u8; TOKEN_LEN]);

impl EnrollmentToken {
    /// The token as typed by the member at enrollment.
    pub fn from_bytes(bytes: [u8; TOKEN_LEN]) -> Self {
        Self(bytes)
    }
}

impl Drop for EnrollmentToken {
    fn drop(&mut self) {
        self.0.fill(0);
        std::hint::black_box(&self.0);
    }
}

impl fmt::Debug for EnrollmentToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("EnrollmentToken(<redacted>)")
    }
}

/// A member's private keys, generated by the Core at enrollment.
pub struct MemberSecrets {
    member_id: Vec<u8>,
    member_sk: HpkePrivateKey,
    inbox_sk: HpkePrivateKey,
}

impl MemberSecrets {
    /// The member these keys belong to.
    pub fn member_id(&self) -> &[u8] {
        &self.member_id
    }

    /// The member public key, derived from the private key the member holds.
    pub fn member_public_key(&self) -> [u8; X25519_LEN] {
        hpke_public_bytes(&self.member_sk)
    }

    /// The personal inbox public key, derived from the private key the member holds.
    pub fn inbox_public_key(&self) -> [u8; X25519_LEN] {
        hpke_public_bytes(&self.inbox_sk)
    }
}

impl fmt::Debug for MemberSecrets {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("MemberSecrets")
            .field("member_id", &String::from_utf8_lossy(&self.member_id))
            .finish_non_exhaustive()
    }
}

/// An adult whose unlock opened their HK wrap: the Core holds HK for them.
pub struct UnlockedAdult {
    member_id: Vec<u8>,
    hk: Secret32,
    hk_version: u32,
}

impl UnlockedAdult {
    /// The unlocked adult.
    pub fn member_id(&self) -> &[u8] {
        &self.member_id
    }

    /// The version of the HK held.
    pub fn hk_version(&self) -> u32 {
        self.hk_version
    }
}

impl fmt::Debug for UnlockedAdult {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("UnlockedAdult")
            .field("member_id", &String::from_utf8_lossy(&self.member_id))
            .field("hk_version", &self.hk_version)
            .finish_non_exhaustive()
    }
}

/// Why a pending member did not receive the HK wrap. Every refusal but
/// [`Refusal::StaleHouseholdKeyVersion`] is a tampering alert to every adult.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Refusal {
    /// The enrollment key was wrapped under another HK version than the unlocking adult's,
    /// as after an HK rotation between `member add` and this unlock. Not tampering: the
    /// member is added again.
    StaleHouseholdKeyVersion,
    /// The wrapped enrollment authentication key did not open under HK: it was edited,
    /// or copied from another record.
    EnrollmentKeyUnwrapFailed,
    /// The enrollment tag did not verify: a public key was substituted or the tag edited.
    EnrollmentTagMismatch,
    /// The record holds a combination of fields no ceremony step writes.
    InconsistentRecord,
}

/// An alert event raised during an adult unlock.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Alert {
    /// The member whose record was refused.
    pub member_id: Vec<u8>,
    /// Why.
    pub refusal: Refusal,
}

/// Outcome of [`adult_unlock_wrap_pending`].
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct UnlockReport {
    /// Members who received the HK wrap.
    pub wrapped: Vec<Vec<u8>>,
    /// Tampering alerts; HK was not wrapped for these members.
    pub alerts: Vec<Alert>,
    /// Members whose pending enrollment predates the current HK version; HK was not
    /// wrapped and they are added again. Not reported as tampering.
    pub stale: Vec<Vec<u8>>,
}

pub(crate) fn token_check(token: &EnrollmentToken, member_id: &[u8]) -> Result<Secret32, Error> {
    hkdf_sha256(&token.0, &[label::ENROLL_TOKEN_CHECK, member_id])
}

pub(crate) fn enrollment_key(token: &EnrollmentToken, member_id: &[u8]) -> Result<Secret32, Error> {
    hkdf_sha256(&token.0, &[label::ENROLL_AUTH, member_id])
}

pub(crate) fn enroll_wrap_key(
    hk: &Secret32,
    member_id: &[u8],
    hk_version: u32,
) -> Result<Secret32, Error> {
    hkdf_sha256(
        hk.expose(),
        &[&versioned_context(
            label::HK_ENROLL_WRAP,
            member_id,
            hk_version,
        )],
    )
}

pub(crate) fn pubkey_mac_key(
    hk: &Secret32,
    member_id: &[u8],
    hk_version: u32,
) -> Result<Secret32, Error> {
    hkdf_sha256(
        hk.expose(),
        &[&versioned_context(label::PUBKEY_MAC, member_id, hk_version)],
    )
}

fn public_keys(record: &MemberRecord) -> Result<(&Tagged32, &Tagged32), Error> {
    match (&record.member_pk, &record.inbox_pk) {
        (Some(member_pk), Some(inbox_pk)) => Ok((member_pk, inbox_pk)),
        _ => Err(Error::WrongState),
    }
}

/// Computes the permanent MAC of `record`'s public keys under the adult's HK.
fn permanent_mac(adult: &UnlockedAdult, record: &MemberRecord) -> Result<PubkeyMac, Error> {
    let (member_pk, inbox_pk) = public_keys(record)?;
    let key = pubkey_mac_key(&adult.hk, &record.member_id, adult.hk_version)?;
    Ok(PubkeyMac {
        hk_version: adult.hk_version,
        tag: hmac_sha256(&key, &mac_input(&record.member_id, member_pk, inbox_pk)?),
    })
}

/// Checks the stored permanent MAC of `record` under the adult's HK.
fn verify_permanent_mac(adult: &UnlockedAdult, record: &MemberRecord) -> Result<(), Error> {
    let (member_pk, inbox_pk) = public_keys(record)?;
    let stored = record.pubkey_mac.as_ref().ok_or(Error::WrongState)?;
    if stored.hk_version != adult.hk_version {
        return Err(Error::PublicKeyMacMismatch);
    }
    let key = pubkey_mac_key(&adult.hk, &record.member_id, stored.hk_version)?;
    let input = mac_input(&record.member_id, member_pk, inbox_pk)?;
    if hmac_sha256_verify(&key, &input, &stored.tag) {
        Ok(())
    } else {
        Err(Error::PublicKeyMacMismatch)
    }
}

/// Seals HK to the record's member public key. The HPKE `info` binds the member and the HK
/// version, the `aad` binds the permanent MAC, so the wrap only opens next to the
/// authenticated public keys it was made for.
fn seal_household_key(
    hk: &Secret32,
    hk_version: u32,
    record: &mut MemberRecord,
    mac: PubkeyMac,
) -> Result<(), Error> {
    let member_pk = record.member_pk.as_ref().ok_or(Error::WrongState)?;
    let info = versioned_context(label::HK_WRAP, &record.member_id, hk_version);
    let (encapped, ciphertext) = hpke_seal(&member_pk.value, &info, &mac.tag, hk)?;
    record.hk_wrap = Some(HkWrap {
        hk_version,
        encapped,
        ciphertext,
    });
    record.pubkey_mac = Some(mac);
    Ok(())
}

fn generate_member_keys(record: &mut MemberRecord) -> MemberSecrets {
    let (member_sk, member_pk) = hpke_generate_keypair();
    let (inbox_sk, inbox_pk) = hpke_generate_keypair();
    record.member_pk = Some(Tagged32::new(alg::PUBLIC_KEY_X25519, member_pk));
    record.inbox_pk = Some(Tagged32::new(alg::PUBLIC_KEY_X25519, inbox_pk));
    MemberSecrets {
        member_id: record.member_id.clone(),
        member_sk,
        inbox_sk,
    }
}

/// Step 5: the first member. Creates `wrappers.db`, HK, the member's key pairs, writes the
/// permanent MAC at once and wraps HK to the member.
pub fn create_first_member(store_path: &Path, member_id: &[u8]) -> Result<MemberSecrets, Error> {
    check_member_id(member_id)?;
    if store_path.exists() {
        return Err(Error::HouseholdExists);
    }
    let hk = Secret32::random()?;
    let mut record = MemberRecord::new(member_id);
    let secrets = generate_member_keys(&mut record);
    let founder = UnlockedAdult {
        member_id: member_id.to_vec(),
        hk,
        hk_version: FIRST_HK_VERSION,
    };
    let mac = permanent_mac(&founder, &record)?;
    seal_household_key(&founder.hk, founder.hk_version, &mut record, mac)?;
    let mut store = Store::empty();
    store.members.push(record);
    store.save(store_path)?;
    Ok(secrets)
}

/// An adult's unlock: opens their HK wrap and checks their own permanent MAC.
pub fn unlock(store_path: &Path, secrets: &MemberSecrets) -> Result<UnlockedAdult, Error> {
    let store = Store::load(store_path)?;
    let record = store
        .member(&secrets.member_id)
        .ok_or(Error::UnknownMember)?;
    if record.state() != MemberState::Active {
        return Err(Error::WrongState);
    }
    let (wrap, mac) = match (&record.hk_wrap, &record.pubkey_mac) {
        (Some(wrap), Some(mac)) => (wrap, mac),
        _ => return Err(Error::WrongState),
    };
    let info = versioned_context(label::HK_WRAP, &record.member_id, wrap.hk_version);
    let hk = hpke_open(
        &secrets.member_sk,
        &wrap.encapped,
        &info,
        &mac.tag,
        &wrap.ciphertext,
    )
    .ok_or(Error::HouseholdKeyUnwrapFailed)?;
    let adult = UnlockedAdult {
        member_id: secrets.member_id.clone(),
        hk,
        hk_version: wrap.hk_version,
    };
    verify_permanent_mac(&adult, record)?;
    Ok(adult)
}

/// Step 2: `vilicus member add` by an unlocked adult. Stores the token check hash and the
/// enrollment authentication key wrapped under a key derived from HK; returns the token.
pub fn member_add(
    store_path: &Path,
    adult: &UnlockedAdult,
    new_member_id: &[u8],
) -> Result<EnrollmentToken, Error> {
    check_member_id(new_member_id)?;
    let mut store = Store::load(store_path)?;
    if store.member(new_member_id).is_some() {
        return Err(Error::MemberExists);
    }
    let mut token = EnrollmentToken([0u8; TOKEN_LEN]);
    SystemRandom::new().fill(&mut token.0)?;

    let check = token_check(&token, new_member_id)?;
    let enroll_key = enrollment_key(&token, new_member_id)?;
    let wrap_key = enroll_wrap_key(&adult.hk, new_member_id, adult.hk_version)?;
    let (nonce, ciphertext) = aead_seal(
        &wrap_key,
        &EnrollKeyWrap::aad(adult.hk_version, new_member_id),
        &enroll_key,
    )?;

    let mut record = MemberRecord::new(new_member_id);
    record.token_check = Some(Tagged32::new(alg::TOKEN_CHECK_HKDF_SHA256, *check.expose()));
    record.enroll_key_wrap = Some(EnrollKeyWrap {
        hk_version: adult.hk_version,
        nonce,
        ciphertext,
    });
    store.members.push(record);
    store.save(store_path)?;
    Ok(token)
}

/// Step 3: enrollment with the token. Checks the token, generates the key pairs and stores
/// the public keys with the enrollment tag. The check hash is erased, so the token is
/// single use; the token and the derived key are dropped on return.
pub fn enroll(
    store_path: &Path,
    member_id: &[u8],
    token: &EnrollmentToken,
) -> Result<MemberSecrets, Error> {
    let mut store = Store::load(store_path)?;
    let record = store.member_mut(member_id).ok_or(Error::TokenRefused)?;
    if record.state() != MemberState::AwaitingEnrollment {
        return Err(Error::TokenRefused);
    }
    let stored_check = record.token_check.as_ref().ok_or(Error::TokenRefused)?;
    let presented_check = token_check(token, member_id)?;
    if !constant_time_eq(presented_check.expose(), &stored_check.value) {
        return Err(Error::TokenRefused);
    }

    let enroll_key = enrollment_key(token, member_id)?;
    let secrets = generate_member_keys(record);
    let (member_pk, inbox_pk) = public_keys(record)?;
    let tag = hmac_sha256(&enroll_key, &mac_input(member_id, member_pk, inbox_pk)?);
    record.enroll_tag = Some(Tagged32::new(alg::MAC_HMAC_SHA256_HKDF_SHA256, tag));
    record.token_check = None;
    store.save(store_path)?;
    Ok(secrets)
}

fn authenticate_and_wrap(adult: &UnlockedAdult, record: &mut MemberRecord) -> Result<(), Refusal> {
    let refuse_inconsistent = |_: Error| Refusal::InconsistentRecord;
    let wrap = record
        .enroll_key_wrap
        .as_ref()
        .ok_or(Refusal::InconsistentRecord)?;
    let tag = record
        .enroll_tag
        .as_ref()
        .ok_or(Refusal::InconsistentRecord)?;
    if wrap.hk_version != adult.hk_version {
        return Err(Refusal::StaleHouseholdKeyVersion);
    }
    let wrap_key = enroll_wrap_key(&adult.hk, &record.member_id, wrap.hk_version)
        .map_err(refuse_inconsistent)?;
    let enroll_key = aead_open(
        &wrap_key,
        &wrap.nonce,
        &EnrollKeyWrap::aad(wrap.hk_version, &record.member_id),
        &wrap.ciphertext,
    )
    .ok_or(Refusal::EnrollmentKeyUnwrapFailed)?;

    let (member_pk, inbox_pk) = public_keys(record).map_err(refuse_inconsistent)?;
    let input = mac_input(&record.member_id, member_pk, inbox_pk).map_err(refuse_inconsistent)?;
    if !hmac_sha256_verify(&enroll_key, &input, &tag.value) {
        return Err(Refusal::EnrollmentTagMismatch);
    }

    let mac = permanent_mac(adult, record).map_err(refuse_inconsistent)?;
    seal_household_key(&adult.hk, adult.hk_version, record, mac).map_err(refuse_inconsistent)?;
    record.enroll_key_wrap = None;
    record.enroll_tag = None;
    Ok(())
}

/// Step 4: at an adult unlock, for each member awaiting HK, unwraps the enrollment
/// authentication key with HK, verifies the enrollment tag, and only then writes the
/// permanent MAC and wraps HK. A refused member gets no wrap and raises an alert, except a
/// pending enrollment made under another HK version, which is reported as stale.
///
/// The delay and veto that precede this step in the product are outside the spike.
pub fn adult_unlock_wrap_pending(
    store_path: &Path,
    adult: &UnlockedAdult,
) -> Result<UnlockReport, Error> {
    let mut store = Store::load(store_path)?;
    let mut report = UnlockReport::default();
    for record in &mut store.members {
        let outcome = match record.state() {
            MemberState::AwaitingHouseholdKey => authenticate_and_wrap(adult, record),
            MemberState::Inconsistent => Err(Refusal::InconsistentRecord),
            MemberState::AwaitingEnrollment | MemberState::Active => continue,
        };
        match outcome {
            Ok(()) => report.wrapped.push(record.member_id.clone()),
            Err(Refusal::StaleHouseholdKeyVersion) => report.stale.push(record.member_id.clone()),
            Err(refusal) => report.alerts.push(Alert {
                member_id: record.member_id.clone(),
                refusal,
            }),
        }
    }
    if !report.wrapped.is_empty() {
        store.save(store_path)?;
    }
    Ok(report)
}

/// A later HK wrap for an active member (for example after the member's wrapper was lost):
/// checks the permanent MAC first and refuses on mismatch.
pub fn rewrap_household_key(
    store_path: &Path,
    adult: &UnlockedAdult,
    member_id: &[u8],
) -> Result<(), Error> {
    let mut store = Store::load(store_path)?;
    let record = store.member_mut(member_id).ok_or(Error::UnknownMember)?;
    if record.state() != MemberState::Active {
        return Err(Error::WrongState);
    }
    verify_permanent_mac(adult, record)?;
    let mac = permanent_mac(adult, record)?;
    seal_household_key(&adult.hk, adult.hk_version, record, mac)?;
    store.save(store_path)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn adult(hk_version: u32) -> UnlockedAdult {
        UnlockedAdult {
            member_id: b"alice".to_vec(),
            hk: Secret32::from_bytes([0x0b; 32]),
            hk_version,
        }
    }

    fn record_with_keys() -> MemberRecord {
        let mut record = MemberRecord::new(b"bob");
        record.member_pk = Some(Tagged32::new(alg::PUBLIC_KEY_X25519, [0x11; 32]));
        record.inbox_pk = Some(Tagged32::new(alg::PUBLIC_KEY_X25519, [0x22; 32]));
        record
    }

    #[test]
    fn mac_under_another_hk_version_fails_hmac_despite_matching_label() {
        let mut record = record_with_keys();
        let mut mac = permanent_mac(&adult(2), &record).expect("mac");
        // Relabel the version-2 MAC as version 1: the equality check passes, the key does not.
        mac.hk_version = 1;
        record.pubkey_mac = Some(mac);
        assert!(matches!(
            verify_permanent_mac(&adult(1), &record),
            Err(Error::PublicKeyMacMismatch)
        ));
    }

    #[test]
    fn mac_under_the_same_hk_version_verifies() {
        let mut record = record_with_keys();
        record.pubkey_mac = Some(permanent_mac(&adult(1), &record).expect("mac"));
        assert!(verify_permanent_mac(&adult(1), &record).is_ok());
    }
}
